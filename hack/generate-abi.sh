#!/bin/bash
set -euo pipefail

ROOT="$(CDPATH='' cd -- "$(dirname "$0")/.." && pwd -P)"
ABI_ROOT="${ROOT}/pkg/abi"

if ! command -v solcjs >/dev/null 2>&1; then
  echo "solcjs is required. Install it with:" >&2
  echo "  npm install -g solc" >&2
  exit 1
fi

if ! command -v abigen >/dev/null 2>&1; then
  echo "abigen is required. Install it with:" >&2
  echo "  go install github.com/ethereum/go-ethereum/cmd/abigen@v1.17.2" >&2
  exit 1
fi

if [[ ! -d "${ABI_ROOT}" ]]; then
  echo "ABI directory not found: ${ABI_ROOT}" >&2
  exit 1
fi

shopt -s nullglob

compile_solidity() {
  local dir="$1"
  local sol_file="$2"
  local abi_file="$3"
  local bin_file="$4"
  local tmp_dir
  local bins
  local non_empty_bins=()
  local generated_bin
  local generated_abi

  tmp_dir="$(mktemp -d)"

  echo "compile ${sol_file#"${ROOT}"/}"
  if ! solcjs --abi --bin --optimize -o "${tmp_dir}" "${sol_file}"; then
    rm -rf "${tmp_dir}"
    return 1
  fi

  bins=("${tmp_dir}"/*.bin)
  for candidate in "${bins[@]}"; do
    if [[ -s "${candidate}" ]]; then
      non_empty_bins+=("${candidate}")
    fi
  done

  if [[ ${#non_empty_bins[@]} -eq 0 ]]; then
    echo "no deployable contract bytecode generated from ${sol_file#"${ROOT}"/}" >&2
    rm -rf "${tmp_dir}"
    return 1
  fi

  if [[ ${#non_empty_bins[@]} -gt 1 ]]; then
    echo "multiple deployable contract bytecode files generated from ${sol_file#"${ROOT}"/}" >&2
    for generated_bin in "${non_empty_bins[@]}"; do
      echo "  - $(basename "${generated_bin}")" >&2
    done
    rm -rf "${tmp_dir}"
    return 1
  fi

  generated_bin="${non_empty_bins[0]}"
  generated_abi="${generated_bin%.bin}.abi"
  if [[ ! -f "${generated_abi}" ]]; then
    echo "ABI file not found for generated bytecode: $(basename "${generated_bin}")" >&2
    rm -rf "${tmp_dir}"
    return 1
  fi

  cp "${generated_abi}" "${abi_file}"
  cp "${generated_bin}" "${bin_file}"
  rm -rf "${tmp_dir}"
}

compiled=0
generated=0

for dir in "${ABI_ROOT}"/*; do
  [[ -d "${dir}" ]] || continue

  name="$(basename "${dir}")"
  abi_file="${dir}/a.abi"
  bin_file="${dir}/b.bin"
  out_file="${dir}/${name}.go"
  sol_files=("${dir}"/*.sol)

  if [[ ${#sol_files[@]} -gt 1 ]]; then
    echo "multiple Solidity files found in ${dir#"${ROOT}"/}; keep exactly one *.sol file" >&2
    for sol_file in "${sol_files[@]}"; do
      echo "  - ${sol_file#"${ROOT}"/}" >&2
    done
    exit 1
  fi

  if [[ ${#sol_files[@]} -eq 1 ]]; then
    compile_solidity "${dir}" "${sol_files[0]}" "${abi_file}" "${bin_file}"
    compiled=$((compiled + 1))
  fi

  if [[ ! -f "${abi_file}" || ! -f "${bin_file}" ]]; then
    continue
  fi

  echo "generate ${out_file#"${ROOT}"/}"
  abigen \
    --abi "${abi_file}" \
    --bin "${bin_file}" \
    --pkg "${name}" \
    --type "${name}" \
    --out "${out_file}"
  generated=$((generated + 1))
done

echo "abi generation complete: compiled=${compiled} generated=${generated}"
